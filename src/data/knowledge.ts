/** โรคตาม CPG ที่ตรงกับข้อความ (ตรวจพบ/อาการ) เรียงตามจำนวนคำที่ตรง */
export function matchConditions(text: string, max = 5): Condition[] {
  const t = text.replace(/ปัตคาด/g, "ปัตฆาต");
  return CONDITIONS.map((c) => ({ c, n: c.keys.filter((k) => t.includes(k)).reduce((a, k) => a + k.length, 0) }))
    .filter((x) => x.n > 0)
    .sort((a, b) => b.n - a.n)
    .slice(0, max)
    .map((x) => x.c);
}

/** ท่ายืดเหยียดที่ตรงกับข้อความ */
export function matchStretches(text: string, max = 2) {
  return STRETCHES.map((s) => ({ s, n: s.keys.filter((k) => text.includes(k)).length }))
    .filter((x) => x.n > 0)
    .sort((a, b) => b.n - a.n)
    .slice(0, max)
    .map((x) => x.s);
}

/** ความรู้ที่เกี่ยวข้องกับเคสนี้ (ส่งให้ AI แบบสั้น ไม่ส่งทั้งคลัง) */
export function knowledgeFor(text: string) {
  return {
    โรคตามCPGที่อาการใกล้เคียง: matchConditions(text).map((c) => `${c.name}${c.code ? ` (${c.code})` : ""}: ${c.signs}`),
    ท่ายืดเหยียดที่เกี่ยวข้อง: matchStretches(text).map((s) => `${s.pose} (${s.group}): ${s.how}${s.dose ? ` · ${s.dose}` : ""}`),
  };
}

/** ข้อควรระวังจากกติกาที่ตรวจได้เองในเครื่อง (ไม่พึ่ง AI) */
export function procCautions(findings: string, procs: string[], ctx: { bloodThinner?: boolean; diabetes?: boolean; age?: number }): string[] {
  const out: string[] = [];
  const hot = /บวม\s*แดง|แดง\s*ร้อน|อักเสบ|บวมร้อน/.test(findings);
  const acute = /(เพิ่ง|เมื่อวาน|วันนี้|ไม่ถึง\s*2\s*วัน).{0,12}(ล้ม|แพลง|เคล็ด|บาดเจ็บ|อุบัติเหตุ)|แพลงเมื่อวาน/.test(findings);
  const compress = procs.some((p) => p.includes("ประคบ"));
  if (hot && compress) out.push("พบ บวม แดง ร้อน/อักเสบ · CPG: ห้ามประคบร้อนช่วงอักเสบเฉียบพลัน 24 ชม.แรก");
  if (acute) out.push("บาดเจ็บไม่ถึง 48 ชม. · ตำรา: ห้ามนวดบริเวณบาดเจ็บภายใน 48 ชม.");
  if (compress && (ctx.diabetes || (ctx.age ?? 0) >= 65)) out.push(`${ctx.diabetes ? "เบาหวาน" : "ผู้สูงอายุ"} · ระวังลูกประคบร้อนเกิน (รับความรู้สึกช้า) ใช้ผ้ารอง`);
  if (ctx.bloodThinner && procs.length) out.push("กินยาละลายลิ่มเลือด · ลดแรงกด ระวังฟกช้ำ");
  return out;
}
