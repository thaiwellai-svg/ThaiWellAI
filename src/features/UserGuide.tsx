export function UserGuide() {
  const [q, setQ] = useState("");
  const [open, setOpen] = useState<string | null>("visits:0");
  const [manual, setManual] = useState(false);
  // "กลับเข้าระบบ" ในคู่มือ (ซ้อนในแอป) → ปิดคู่มือ
  useEffect(() => {
    if (!manual) return;
    const on = (e: MessageEvent) => e.data === "tw-close-manual" && setManual(false);
    window.addEventListener("message", on);
    return () => window.removeEventListener("message", on);
  }, [manual]);
  const needle = q.trim().toLowerCase();
  const chapters = CHAPTERS.map((c) => ({
    ...c,
    topics: c.topics.map((t, k) => ({ ...t, k })).filter((t) => !needle || `${c.title} ${t.q} ${t.steps.join(" ")} ${t.tip ?? ""}`.toLowerCase().includes(needle)),
  })).filter((c) => c.topics.length);

  return (
    <div className="ug">
      <div className="ug-hero">
        <span className="ug-hero__icon">
          <GraduationCap size={26} />
        </span>
        <div>
          <b>คู่มือการใช้งาน ThaiWell</b>
          <small>วิธีใช้ทุกเมนูทีละขั้น</small>
        </div>
        <div className="ug-hero__btns">
          <a
            className="is-main"
            href={`${import.meta.env.BASE_URL}tutorial/`}
            target="_blank"
            rel="noopener"
            onClick={(e) => {
              // แอป iPad (Capacitor) เปิดแท็บใหม่ไม่ได้ → เปิดคู่มือเต็มจอในแอปแทน
              if (isNativeApp()) {
                e.preventDefault();
                setManual(true);
              }
            }}
          >
            <MonitorPlay size={16} /> ดูคู่มือฉบับเต็ม
          </a>
          <button type="button" onClick={startTour}>
            <PlayCircle size={16} /> แนะนำเมนู
          </button>
        </div>
      </div>

      <label className="ug-search">
        <Search size={16} />
        <input value={q} onChange={(e) => setQ(e.target.value)} placeholder="ค้นหาวิธีใช้ เช่น ลงทะเบียน คืนเงิน หุ่น 3D" />
      </label>

      {chapters.length === 0 && <p className="ug-empty">ไม่พบหัวข้อ “{q}”</p>}

      {chapters.map((c) => (
        <section key={c.id} className="ug-ch" style={{ ["--c" as string]: c.color }}>
          <header>
            <span className="ug-ch__icon">
              <c.Icon width={18} height={18} />
            </span>
            <div>
              <b>{c.title}</b>
              <small>{c.intro}</small>
            </div>
          </header>
          <div className="ug-list">
            {c.topics.map((t) => {
              const id = `${c.id}:${t.k}`;
              const on = open === id || !!needle;
              return (
                <div key={id} className={on ? "ug-item is-open" : "ug-item"}>
                  <button type="button" onClick={() => setOpen(open === id ? null : id)} aria-expanded={on}>
                    {t.q}
                    <ChevronDown size={16} />
                  </button>
                  <AnimatePresence initial={false}>
                    {on && (
                      <motion.div className="ug-body" initial={{ height: 0, opacity: 0 }} animate={{ height: "auto", opacity: 1 }} exit={{ height: 0, opacity: 0 }} transition={{ duration: 0.22 }}>
                        <ol>
                          {t.steps.map((s, n) => (
                            <li key={n}>
                              <i>{n + 1}</i>
                              {s}
                            </li>
                          ))}
                        </ol>
                        {t.tip && (
                          <p className="ug-tip">
                            <Lightbulb size={14} /> {t.tip}
                          </p>
                        )}
                      </motion.div>
                    )}
                  </AnimatePresence>
                </div>
              );
            })}
          </div>
        </section>
      ))}
      {/* คู่มือฉบับเต็มในแอป iPad: เต็มจอ ปิดได้ (เว็บเปิดแท็บใหม่ตามเดิม) */}
      {manual &&
        createPortal(
          <div className="ug-manual" role="dialog" aria-label="คู่มือฉบับเต็ม">
            <iframe src={`${import.meta.env.BASE_URL}tutorial/index.html`} title="คู่มือการใช้งาน ThaiWell" />
            <button type="button" className="ug-manual__close" onClick={() => setManual(false)} aria-label="ปิดคู่มือ">
              <X size={20} />
            </button>
          </div>,
          document.body,
        )}
    </div>
  );
}
